// renderPersonaBehaviors emits the persona-behaviours block that replaces the
// Jinja2 {% for b in persona.behaviors %} loop in adk-python's template.
func renderPersonaBehaviors(persona *models.UserPersona, stopSignal string) string {
	if persona == nil || len(persona.Behaviors) == 0 {
		return ""
	}
	var b strings.Builder
	for _, beh := range persona.Behaviors {
		fmt.Fprintf(&b, "\n## Criteria: %s\n", beh.Name)
		if beh.Description != "" {
			b.WriteString(strings.ReplaceAll(beh.Description, "{{ stop_signal }}", stopSignal))
			b.WriteString("\n")
		}
		if len(beh.ViolationRubrics) > 0 {
			b.WriteString("\nMark as FAIL if any of the following Violations occur:\n")
			for _, v := range beh.ViolationRubrics {
				fmt.Fprintf(&b, "- %s\n", strings.ReplaceAll(v, "{{ stop_signal }}", stopSignal))
			}
		}
	}
	return b.String()
}

// formatConversationHistory joins invocation user/agent turns into the
// "role: text" per-line block Python builds via _format_conversation_history.
func formatConversationHistory(invs []models.Invocation) string {
	var lines []string
	for _, inv := range invs {
		if inv.UserContent != nil && len(inv.UserContent.Parts) > 0 {
			userText := textFromContent(inv.UserContent)
			if userText != "" {
				lines = append(lines, "user: "+userText)
			}
		}
		if inv.FinalResponse != nil {
			role := inv.FinalResponse.Role
			if role == "" {
				role = "model"
			}
			finalText := textFromContent(inv.FinalResponse)
			if finalText != "" {
				lines = append(lines, role+": "+finalText)
			}
		}
	}
	return strings.Join(lines, "\n\n")
}

// formatPerTurnSimulatorPrompt builds the per-turn user simulator quality
// prompt, selecting the persona-free or persona template based on scenario.
func formatPerTurnSimulatorPrompt(
	generatedUserResponse string,
	history []models.Invocation,
	scenario *models.ConversationScenario,
	stopSignal string,
) string {
	if scenario == nil {
		return ""
	}
	convHistory := formatConversationHistory(history)
	if scenario.UserPersona == nil {
		repl := strings.NewReplacer(
			"{{stop_signal}}", stopSignal,
			"{{conversation_plan}}", scenario.ConversationPlan,
			"{{conversation_history}}", convHistory,
			"{{generated_user_response}}", generatedUserResponse,
		)
		return repl.Replace(simulatorPromptNoPersona)
	}
	criteria := renderPersonaBehaviors(scenario.UserPersona, stopSignal)
	repl := strings.NewReplacer(
		"{{stop_signal}}", stopSignal,
		"{{conversation_plan}}", scenario.ConversationPlan,
		"{{conversation_history}}", convHistory,
		"{{generated_user_response}}", generatedUserResponse,
		"{{persona_description}}", scenario.UserPersona.Description,
		"{{persona_criteria}}", criteria,
	)
	return repl.Replace(simulatorPromptWithPersona)
}

// isValidRe mirrors adk-python's regex at
// per_turn_user_simulator_quality_v1.py:58-61.
var isValidRe = regexp.MustCompile(`"is_valid"\s*:\s*\[*[\n\s]*"*([^"\]]*)"*[\n\s]*\]*\s*[,\n\}]`)

// parseIsValidJSON extracts the is_valid label from the judge response,
// tolerating array/whitespace variants and mapping labels to 0.0/1.0 (matches
// Python _parse_llm_response).
func parseIsValidJSON(response string) (float64, error) {
	m := isValidRe.FindStringSubmatch(response)
	if m == nil {
		return 0, fmt.Errorf(`missing "is_valid" field in judge response`)
	}
	v := strings.ToLower(strings.TrimSpace(m[1]))
	v = strings.Trim(v, `,}"`)
	v = strings.TrimSpace(v)
	switch v {
	case "true", "valid":
		return 1.0, nil
	case "false", "invalid", "almost", "partially_valid", "partially":
		return 0.0, nil
	}
	return 0, fmt.Errorf(`unrecognized is_valid value %q`, v)
}
