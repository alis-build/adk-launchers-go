// effectiveRubrics unions criterion-level rubrics with per-invocation rubrics,
// rejecting duplicate rubric IDs (matches Python create_effective_rubrics_list).
func effectiveRubrics(criterion []models.Rubric, invRubrics []models.Rubric) ([]models.Rubric, error) {
	seen := make(map[string]struct{}, len(criterion)+len(invRubrics))
	out := make([]models.Rubric, 0, len(criterion)+len(invRubrics))
	add := func(src []models.Rubric, scope string) error {
		for _, r := range src {
			if _, dup := seen[r.RubricID]; dup {
				return fmt.Errorf("rubric with rubric_id %q already exists (%s)", r.RubricID, scope)
			}
			seen[r.RubricID] = struct{}{}
			out = append(out, r)
		}
		return nil
	}
	if err := add(criterion, "criterion"); err != nil {
		return nil, err
	}
	if err := add(invRubrics, "invocation"); err != nil {
		return nil, err
	}
	return out, nil
}

// renderRubricsList emits the "*  <text_property>" bullet list Python builds
// when populating {rubrics} in the final-response and tool-use templates.
func renderRubricsList(rubrics []models.Rubric) string {
	var b strings.Builder
	for _, r := range rubrics {
		if r.RubricContent.TextProperty == nil {
			continue
		}
		fmt.Fprintf(&b, "*  %s\n", *r.RubricContent.TextProperty)
	}
	return strings.TrimRight(b.String(), "\n")
}

// renderRubricsPropertiesJSON emits the JSON list of {property, type} entries
// used by the multi-turn-trajectory template (matches Python at
// rubric_based_multi_turn_trajectory_evaluator.py:349-357).
func renderRubricsPropertiesJSON(rubrics []models.Rubric) string {
	type entry struct {
		Property string `json:"property"`
		Type     string `json:"type,omitempty"`
	}
	list := make([]entry, 0, len(rubrics))
	for _, r := range rubrics {
		var text string
		if r.RubricContent.TextProperty != nil {
			text = *r.RubricContent.TextProperty
		}
		e := entry{Property: text}
		if r.Type != nil {
			e.Type = *r.Type
		}
		list = append(list, e)
	}
	buf, err := json.MarshalIndent(list, "", "  ")
	if err != nil {
		return ""
	}
	return string(buf)
}

// renderDeveloperInstructions returns the developer-instructions text for the
// named agent, or "" when unavailable (matches Python fallback).
func renderDeveloperInstructions(app *models.AppDetails, agentName string) string {
	if app == nil || agentName == "" {
		return ""
	}
	details, ok := app.AgentDetails[agentName]
	if !ok {
		return ""
	}
	return details.Instructions
}

// renderAllDeveloperInstructions concatenates instructions across every agent
// in AppDetails (used by the multi-turn template's {agent_instructions} slot).
func renderAllDeveloperInstructions(app *models.AppDetails) string {
	if app == nil || len(app.AgentDetails) == 0 {
		return ""
	}
	var parts []string
	seen := make(map[string]struct{})
	for name, d := range app.AgentDetails {
		if d.Instructions == "" {
			continue
		}
		block := fmt.Sprintf("Agent %s Instructions:\n%s", name, d.Instructions)
		if _, ok := seen[block]; ok {
			continue
		}
		seen[block] = struct{}{}
		parts = append(parts, block)
	}
	return strings.Join(parts, "\n\n")
}

// renderToolDeclarationsJSON emits the {tool_declarations} slot content:
// "Agent has no tools." when AppDetails is nil or empty; else a JSON object
// keyed by agent name mapping to the raw tool declarations.
func renderToolDeclarationsJSON(app *models.AppDetails) string {
	if app == nil || len(app.AgentDetails) == 0 {
		return "Agent has no tools."
	}
	byAgent := make(map[string][]*genai.Tool, len(app.AgentDetails))
	found := false
	for name, d := range app.AgentDetails {
		if len(d.ToolDeclarations) == 0 {
			continue
		}
		byAgent[name] = d.ToolDeclarations
		found = true
	}
	if !found {
		return "Agent has no tools."
	}
	wrapper := map[string]any{"tool_declarations": byAgent}
	buf, err := json.MarshalIndent(wrapper, "", "  ")
	if err != nil {
		return "Agent has no tools."
	}
	return string(buf)
}

// renderAllToolDefinitions builds the {agent_tool_definitions} slot content
// used by the multi-turn template: one line per (agent, tool) pair.
func renderAllToolDefinitions(app *models.AppDetails) string {
	if app == nil || len(app.AgentDetails) == 0 {
		return ""
	}
	var lines []string
	seen := make(map[string]struct{})
	for name, d := range app.AgentDetails {
		agentLine := fmt.Sprintf("Agent: %s", name)
		if _, ok := seen[agentLine]; !ok {
			seen[agentLine] = struct{}{}
			lines = append(lines, agentLine)
		}
		for _, tool := range d.ToolDeclarations {
			if tool == nil {
				continue
			}
			for _, fn := range tool.FunctionDeclarations {
				if fn == nil {
					continue
				}
				line := fmt.Sprintf("- %s: %s", fn.Name, fn.Description)
				if _, ok := seen[line]; ok {
					continue
				}
				seen[line] = struct{}{}
				lines = append(lines, line)
			}
		}
	}
	return strings.Join(lines, "\n")
}

// renderToolCallsAndResponsesJSON marshals tool calls paired with responses
// to JSON matching Python get_tool_calls_and_responses_as_json_str.
func renderToolCallsAndResponsesJSON(inv models.Invocation) string {
	pairs, err := models.GetAllToolCallsWithResponses(inv.IntermediateData)
	if err != nil || len(pairs) == 0 {
		return "[]"
	}
	type serialized struct {
		ToolCall     *genai.FunctionCall     `json:"tool_call,omitempty"`
		ToolResponse *genai.FunctionResponse `json:"tool_response,omitempty"`
	}
	list := make([]serialized, 0, len(pairs))
	for _, p := range pairs {
		list = append(list, serialized{ToolCall: p.Call, ToolResponse: p.Response})
	}
	wrapper := map[string]any{"tool_calls_and_response": list}
	buf, err := json.MarshalIndent(wrapper, "", "  ")
	if err != nil {
		return "[]"
	}
	return string(buf)
}

// firstEventAuthor returns the author of the first InvocationEvents entry, or
// "" when unavailable (matches Python's invocation_events[0].author lookup).
func firstEventAuthor(inv models.Invocation) string {
	events, ok := inv.IntermediateData.AsInvocationEvents()
	if !ok || events == nil || len(events.InvocationEvents) == 0 {
		return ""
	}
	return events.InvocationEvents[0].Author
}

// formatRubricFinalResponsePrompt renders the final-response quality prompt.
//
// The expected invocation is intentionally unused: adk-python's rubric
// judges score the actual final response against the rubrics only, using
// the rubric text (not a golden reference) as the source of truth. The
// argument is retained to satisfy the shared formatPrompt signature on
// llmJudgeEvaluator.
func formatRubricFinalResponsePrompt(actual models.Invocation, _ *models.Invocation, rubrics []models.Rubric) string {
	repl := strings.NewReplacer(
		"{developer_instructions}", renderDeveloperInstructions(actual.AppDetails, firstEventAuthor(actual)),
		"{tool_declarations}", renderToolDeclarationsJSON(actual.AppDetails),
		"{user_input}", textFromContent(actual.UserContent),
		"{response_steps}", renderToolCallsAndResponsesJSON(actual),
		"{final_response}", textFromContent(actual.FinalResponse),
		"{rubrics}", renderRubricsList(rubrics),
	)
	return repl.Replace(rubricPromptFinalResponseV1)
}

// formatRubricToolUsePrompt renders the tool-use quality prompt.
func formatRubricToolUsePrompt(actual models.Invocation, rubrics []models.Rubric) string {
	repl := strings.NewReplacer(
		"{tool_declarations}", renderToolDeclarationsJSON(actual.AppDetails),
		"{user_input}", textFromContent(actual.UserContent),
		"{tool_usage}", renderToolCallsAndResponsesJSON(actual),
		"{rubrics}", renderRubricsList(rubrics),
	)
	return repl.Replace(rubricPromptToolUseV1)
}

// formatRubricMultiTurnPrompt renders the multi-turn trajectory prompt with the
// full assembled conversation history across all invocations.
func formatRubricMultiTurnPrompt(actuals []models.Invocation, rubrics []models.Rubric) string {
	// Build merged AppDetails across turns for the instructions/tools slots.
	merged := &models.AppDetails{AgentDetails: map[string]models.AgentDetails{}}
	for _, inv := range actuals {
		if inv.AppDetails == nil {
			continue
		}
		for name, d := range inv.AppDetails.AgentDetails {
			if _, ok := merged.AgentDetails[name]; ok {
				continue
			}
			merged.AgentDetails[name] = d
		}
	}
	if len(merged.AgentDetails) == 0 {
		merged = nil
	}
	repl := strings.NewReplacer(
		"{agent_instructions}", renderAllDeveloperInstructions(merged),
		"{agent_tool_definitions}", renderAllToolDefinitions(merged),
		"{user_agent_dialogue}", assembleDialogueHistory(actuals),
		"{properties}", renderRubricsPropertiesJSON(rubrics),
	)
	return repl.Replace(rubricPromptMultiTurnV1)
}

// assembleDialogueHistory formats the multi-turn conversation for the judge
// prompt (matches Python _assemble_dialogue_history).
func assembleDialogueHistory(actuals []models.Invocation) string {
	var lines []string
	for i, inv := range actuals {
		turn := i + 1
		if inv.UserContent != nil && len(inv.UserContent.Parts) > 0 {
			userText := textFromContent(inv.UserContent)
			if userText != "" {
				lines = append(lines, fmt.Sprintf("USER TURN %d: %s", turn, userText))
			}
		}
		agentName := firstEventAuthor(inv)
		if agentName == "" {
			agentName = "agent"
		}
		if events, ok := inv.IntermediateData.AsInvocationEvents(); ok && events != nil {
			for _, ev := range events.InvocationEvents {
				if ev.Content == nil || len(ev.Content.Parts) == 0 {
					continue
				}
				role := "AGENT (" + ev.Author + ")"
				if strings.EqualFold(ev.Author, "user") {
					role = "USER"
				}
				var texts []string
				for _, p := range ev.Content.Parts {
					if p == nil {
						continue
					}
					if p.Text != "" {
						texts = append(texts, p.Text)
					}
				}
				if len(texts) > 0 {
					lines = append(lines, fmt.Sprintf("%s TURN %d: %s", role, turn, strings.Join(texts, " ")))
				}
				for _, p := range ev.Content.Parts {
					if p == nil {
						continue
					}
					if p.FunctionCall != nil {
						args := "{}"
						if len(p.FunctionCall.Args) > 0 {
							if b, err := json.Marshal(p.FunctionCall.Args); err == nil {
								args = string(b)
							}
						}
						lines = append(lines, fmt.Sprintf("%s TURN %d (tool call): %s(%s)", role, turn, p.FunctionCall.Name, args))
					}
					if p.FunctionResponse != nil {
						resp := "{}"
						if len(p.FunctionResponse.Response) > 0 {
							if b, err := json.Marshal(p.FunctionResponse.Response); err == nil {
								resp = string(b)
							}
						}
						lines = append(lines, fmt.Sprintf("%s TURN %d (tool output): %s -> %s", role, turn, p.FunctionResponse.Name, resp))
					}
				}
			}
		}
		if inv.FinalResponse != nil && len(inv.FinalResponse.Parts) > 0 {
			finalText := textFromContent(inv.FinalResponse)
			if finalText != "" {
				role := "AGENT (" + agentName + ")"
				candidate := fmt.Sprintf("%s TURN %d: %s", role, turn, finalText)
				// Skip when the same final text was already emitted from an
				// InvocationEvent (defensive against legacy/hand-authored
				// eval sets whose intermediate data contains the final turn).
				if len(lines) == 0 || lines[len(lines)-1] != candidate {
					lines = append(lines, candidate)
				}
			}
		}
	}
	return strings.Join(lines, "\n")
}
